-- ============================================================================
-- Role matrix test — Phase A2
--
-- Proves the capability table in MULTI_TENANT_DESIGN.md §5: staff can run the
-- kiosk but not change it, admins can change it but cannot touch owners, owners
-- can do everything except leave the org without an owner.
--
-- HOW TO RUN: paste the whole file into the Supabase SQL editor and run it.
--   * Runs inside BEGIN … ROLLBACK — it writes nothing, pass or fail.
--   * Success -> a table of every check, all 'pass', ending ALL CHECKS PASSED.
--   * Failure -> a red error naming the capability that was wrong.
--
-- Two different refusal shapes are asserted, and the difference matters:
--   * INSERT against a WITH CHECK is REFUSED (error 42501).
--   * UPDATE/DELETE against a USING clause simply MATCHES NOTHING (0 rows),
--     because a row the caller may not touch is invisible to the statement.
-- ============================================================================

begin;

create table public._role_results (
  n          int generated by default as identity primary key,
  acting_as  text not null,
  check_name text not null,
  result     text not null default 'pass'
);
-- Supabase enables RLS on tables newly created in public; this scratch table
-- holds no tenant data and dies with the rollback.
alter table public._role_results disable row level security;
grant insert on public._role_results to authenticated;

